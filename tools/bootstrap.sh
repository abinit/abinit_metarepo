#!/usr/bin/env bash
# Set up abimeta for this machine: a small tooling venv with PyYAML, an `abimeta` wrapper on PATH, and a
# personal config template. Run it from the main clone of the meta repo; rerunning it is safe.
#
#   tools/bootstrap.sh [--dev]      # --dev also installs pytest
#
# Environment overrides: ABIMETA_PYTHON (interpreter, must be >= 3.11), ABIMETA_BIN_DIR (default ~/.local/bin),
# XDG_CONFIG_HOME (default ~/.config).
set -euo pipefail

dev=0
[[ "${1:-}" == "--dev" ]] && dev=1

main_clone="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/abinit_metarepo"
venv="$config_dir/venv"
bin_dir="${ABIMETA_BIN_DIR:-$HOME/.local/bin}"

find_python() {
    local cands=("${ABIMETA_PYTHON:-}" python3.14 python3.13 python3.12 python3.11 python3)
    for p in "${cands[@]}"; do
        [[ -z "$p" ]] && continue
        command -v "$p" >/dev/null 2>&1 || continue
        if "$p" -c 'import sys; sys.exit(sys.version_info < (3, 11))' 2>/dev/null; then
            command -v "$p"
            return 0
        fi
    done
    return 1
}

python="$(find_python)" || { echo "bootstrap: no Python >= 3.11 found; set ABIMETA_PYTHON" >&2; exit 1; }
echo "python: $python ($("$python" --version))"

mkdir -p "$config_dir" "$bin_dir"
pkgs=(pyyaml)
(( dev )) && pkgs+=(pytest)

if command -v uv >/dev/null 2>&1; then
    [[ -x "$venv/bin/python" ]] || uv venv --python "$python" "$venv"
    uv pip install --python "$venv/bin/python" "${pkgs[@]}"
else
    [[ -x "$venv/bin/python" ]] || "$python" -m venv "$venv"
    "$venv/bin/python" -m pip install --quiet --upgrade "${pkgs[@]}"
fi
echo "venv: $venv"

wrapper="$bin_dir/abimeta"
cat > "$wrapper" <<EOF
#!/bin/sh
# Generated by $main_clone/tools/bootstrap.sh
exec "$venv/bin/python" "$main_clone/tools/abimeta.py" "\$@"
EOF
chmod +x "$wrapper"
echo "wrapper: $wrapper"

config="$config_dir/config.yaml"
if [[ ! -e "$config" ]]; then
    cat > "$config" <<'EOF'
# Personal abimeta config (never committed). See plans/plan_metarepo.md, "Forges and identities".

# Username and protocol (ssh or https) on each forge listed in repos.yaml.
identities:
  gitlab.uliege.be: { user: CHANGEME, protocol: ssh }
  github.com:       { user: CHANGEME, protocol: ssh }

# Where feature workspaces (meta_<feature>/) are created. Default: the parent of the main clone.
# workspace_root: ~/git_repos

# Meta repo URL to clone from. Default: the main clone's origin.
# meta_remote: git@github.com:abinit/abinit_metarepo.git

# Repos you push to directly, without a fork.
# no_fork: [abipy]

# Colleague forks to add as remotes in new clones: remote name -> username on that forge.
# extra_remotes:
#   abinit: { hexu: X.He, siyu: SiyuChern }

# Partial clones to save disk and time, e.g. blob:none.
# clone_filter: blob:none
EOF
    echo "config: wrote template $config: edit the CHANGEME entries"
else
    echo "config: $config (kept)"
fi

case ":$PATH:" in
    *":$bin_dir:"*) ;;
    *) echo "NOTE: $bin_dir is not on PATH; add it to your shell profile" ;;
esac
